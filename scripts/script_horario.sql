	PRIMARY KEY("id_dia")
);

CREATE TABLE IF NOT EXISTS "hora_catedra" (
	"id_hora_catedra" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"numero_franja" INTEGER,
