);

CREATE TABLE IF NOT EXISTS "cuatrimestre" (
	"id_cuatrimestre" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"nombre" VARCHAR(255),
	"numero" INTEGER,
	"fecha_desde" DATE,
	"fecha_hasta" DATE,
