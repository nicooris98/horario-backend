CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(150) UNIQUE,
    password VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
	created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- =========================================================
-- ACTIVACION DE CUENTAS Y CONFIGURACION INICIAL DE CONTRASENA
-- Reejecutable: conserva los usuarios y desafios existentes.
-- =========================================================

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS is_disabled BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER COLUMN password DROP NOT NULL;

CREATE TABLE IF NOT EXISTS account_activation_challenges (
    user_id INTEGER NOT NULL PRIMARY KEY,
    code_hash CHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    failed_attempts SMALLINT NOT NULL DEFAULT 0,
    last_sent_at TIMESTAMP WITH TIME ZONE NOT NULL,
    send_window_started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sends_in_window SMALLINT NOT NULL DEFAULT 1,
    consumed_at TIMESTAMP WITH TIME ZONE,
    password_setup_token_hash CHAR(64),
    password_setup_token_expires_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    CONSTRAINT "FK_account_activation_challenges_user_id"
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE CASCADE ON UPDATE NO ACTION,
    CONSTRAINT "CHK_account_activation_failed_attempts"
        CHECK (failed_attempts >= 0 AND failed_attempts <= 5),
    CONSTRAINT "CHK_account_activation_sends_in_window"
        CHECK (sends_in_window >= 1 AND sends_in_window <= 5),
    CONSTRAINT "CHK_account_activation_password_setup_token_pair"
        CHECK (
            (password_setup_token_hash IS NULL) =
            (password_setup_token_expires_at IS NULL)
        )
);

ALTER TABLE account_activation_challenges
    ADD COLUMN IF NOT EXISTS password_setup_token_hash CHAR(64),
    ADD COLUMN IF NOT EXISTS password_setup_token_expires_at TIMESTAMP WITH TIME ZONE;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'CHK_account_activation_password_setup_token_pair'
          AND conrelid = 'account_activation_challenges'::regclass
    ) THEN
        ALTER TABLE account_activation_challenges
            ADD CONSTRAINT "CHK_account_activation_password_setup_token_pair"
            CHECK (
                (password_setup_token_hash IS NULL) =
                (password_setup_token_expires_at IS NULL)
            );
    END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS "UQ_account_activation_password_setup_token"
    ON account_activation_challenges (password_setup_token_hash)
    WHERE password_setup_token_hash IS NOT NULL;

